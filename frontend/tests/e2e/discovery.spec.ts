import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

test('real database discovery exposes schema and composite relationships without source values', async ({ page }, testInfo) => {
  const passwordPath = process.env.PS_E2E_PASSWORD_FILE;
  if (!passwordPath) throw new Error('Set PS_E2E_PASSWORD_FILE to an existing account password file before running test:e2e.');
  const password = (await readFile(passwordPath, 'utf8')).replace(/[\r\n]+$/, '');
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.name));
  await page.goto('/connections');
  await page.getByLabel('Email address').fill(process.env.PS_E2E_ADMIN_EMAIL ?? 'admin@example.com');
  await page.getByLabel('Password', { exact: true }).fill(password).catch(() => {
    throw new Error('The login password field could not be filled.');
  });
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Connections.' })).toBeVisible();
  const card = page.getByRole('article', { name: `Connection ${process.env.PS_E2E_CONNECTION_NAME ?? 'Synthetic enterprise'}` });
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: 'Test connection', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'is reachable.' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('connections-desktop.png'), fullPage: true });
  await page.getByLabel('Schemas to inspect').fill('enterprise');
  await card.getByRole('button', { name: 'Discover schema', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Schema Explorer.' })).toBeVisible();
  const tableList = page.getByRole('complementary', { name: 'Discovered tables' });
  await expect(tableList.getByRole('button')).toHaveCount(4);
  await tableList.getByRole('button', { name: 'customers', exact: true }).click();
  await expect(page.getByRole('table').getByText('JSONB', { exact: true })).toBeVisible();
  await expect(page.getByRole('table').getByRole('rowheader', { name: /profile/ })).toBeVisible();
  await tableList.getByRole('button', { name: 'transactions', exact: true }).click();
  await expect(page.getByText('Composite primary key', { exact: true })).toBeVisible();
  await expect(page.getByText('account_id + sequence_number', { exact: true })).toBeVisible();
  await tableList.getByRole('button', { name: 'support_records', exact: true }).click();
  await expect(page.getByText('Composite foreign key', { exact: true })).toBeVisible();
  await expect(page.getByText('related_account_id, related_sequence_number', { exact: true })).toBeVisible();
  await expect(page.getByText('(account_id, sequence_number)', { exact: true })).toBeVisible();
  await expect(page.getByText('customer1@example.com', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('schema-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'enterprise.transactions', exact: true }).click();
  await expect(page.getByText('Composite primary key', { exact: true })).toBeVisible();
  await page.getByLabel('Find columns').fill('sequence');
  await expect(page.getByRole('table').getByRole('row')).toHaveCount(2);
  await page.getByLabel('Find columns').clear();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath('schema-mobile.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Schema Explorer.' })).toBeVisible();
  await expect(tableList.getByRole('button')).toHaveCount(4);
  expect(errors).toEqual([]);
});
